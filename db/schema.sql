SET client_encoding = 'UTF8';

-- Схема БД «Склад магазина» (вариант 3).
-- PostgreSQL 14+.
-- Денежные значения хранятся в сотых долях белорусского рубля (капейках), BIGINT;

BEGIN;

CREATE TABLE IF NOT EXISTS product_categories (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(120) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS suppliers (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(160) NOT NULL UNIQUE,
    inn          VARCHAR(20) NOT NULL DEFAULT '',
    contact      VARCHAR(200) NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS products (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku              VARCHAR(50) NOT NULL UNIQUE,
    name             VARCHAR(200) NOT NULL,
    category_id      BIGINT NOT NULL REFERENCES product_categories(id),
    unit             VARCHAR(20) NOT NULL DEFAULT 'шт',
    sale_price_cents BIGINT NOT NULL CHECK (sale_price_cents >= 0),
    tax_rate_bp      INTEGER NOT NULL DEFAULT 2000 CHECK (tax_rate_bp BETWEEN 0 AND 10000),
    shelf_life_days  INTEGER NOT NULL DEFAULT 30 CHECK (shelf_life_days > 0),
    min_stock        INTEGER NOT NULL DEFAULT 0 CHECK (min_stock >= 0),
    is_active        BOOLEAN NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS supplies (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id  BIGINT NOT NULL REFERENCES suppliers(id),
    invoice_no   VARCHAR(80) NOT NULL DEFAULT '',
    supplied_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    note         TEXT NOT NULL DEFAULT '',
    UNIQUE (supplier_id, invoice_no)
);

-- Каждая строка — партия товара с собственной закупочной ценой и сроком годности.
CREATE TABLE IF NOT EXISTS supply_items (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supply_id           BIGINT NOT NULL REFERENCES supplies(id) ON DELETE CASCADE,
    product_id          BIGINT NOT NULL REFERENCES products(id),
    quantity            INTEGER NOT NULL CHECK (quantity > 0),
    remaining_quantity  INTEGER NOT NULL
                        CHECK (remaining_quantity >= 0 AND remaining_quantity <= quantity),
    unit_cost_cents     BIGINT NOT NULL CHECK (unit_cost_cents >= 0),
    expiry_date         DATE NOT NULL,
    UNIQUE (supply_id, product_id)
);

CREATE TABLE IF NOT EXISTS sales (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sold_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    note        TEXT NOT NULL DEFAULT ''
);

-- В sale_items сохраняется финансовый результат на момент продажи.
CREATE TABLE IF NOT EXISTS sale_items (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id           BIGINT NOT NULL REFERENCES sales(id) ON DELETE CASCADE,
    product_id        BIGINT NOT NULL REFERENCES products(id),
    quantity          INTEGER NOT NULL CHECK (quantity > 0),
    unit_price_cents  BIGINT NOT NULL CHECK (unit_price_cents >= 0),
    revenue_cents     BIGINT NOT NULL CHECK (revenue_cents >= 0),
    tax_cents         BIGINT NOT NULL CHECK (tax_cents >= 0),
    cost_cents        BIGINT NOT NULL CHECK (cost_cents >= 0),
    profit_cents      BIGINT NOT NULL,
    CONSTRAINT ck_sale_revenue
        CHECK (revenue_cents = quantity::BIGINT * unit_price_cents),
    CONSTRAINT ck_sale_profit
        CHECK (profit_cents = revenue_cents - tax_cents - cost_cents)
);

-- Списание всегда относится к конкретной партии: так виден срок годности.
CREATE TABLE IF NOT EXISTS write_offs (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id     BIGINT NOT NULL REFERENCES products(id),
    supply_item_id BIGINT NOT NULL REFERENCES supply_items(id),
    quantity       INTEGER NOT NULL CHECK (quantity > 0),
    reason         VARCHAR(20) NOT NULL
                   CHECK (reason IN ('EXPIRED', 'DAMAGED', 'OTHER')),
    cost_cents     BIGINT NOT NULL CHECK (cost_cents >= 0),
    written_off_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    comment        TEXT NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS ix_supply_items_product_expiry
    ON supply_items(product_id, expiry_date);
CREATE INDEX IF NOT EXISTS ix_supply_items_expiry_remaining
    ON supply_items(expiry_date) WHERE remaining_quantity > 0;
CREATE INDEX IF NOT EXISTS ix_sales_sold_at ON sales(sold_at);
CREATE INDEX IF NOT EXISTS ix_sale_items_product ON sale_items(product_id);
CREATE INDEX IF NOT EXISTS ix_write_offs_reason_date ON write_offs(reason, written_off_at);

DROP VIEW IF EXISTS v_product_stock;
CREATE VIEW v_product_stock AS
SELECT
    p.id AS product_id,
    p.sku,
    p.name,
    c.name AS category,
    p.unit,
    p.sale_price_cents,
    p.tax_rate_bp,
    p.shelf_life_days,
    p.min_stock,
    COALESCE(SUM(si.remaining_quantity), 0)::INTEGER AS stock_quantity,
    COALESCE(SUM(si.remaining_quantity::BIGINT * si.unit_cost_cents), 0)::BIGINT
        AS stock_cost_cents,
    MIN(si.expiry_date) FILTER (WHERE si.remaining_quantity > 0) AS nearest_expiry,
    CASE
        WHEN COALESCE(SUM(si.remaining_quantity), 0) = 0 THEN 'OUT'
        WHEN MIN(si.expiry_date) FILTER (WHERE si.remaining_quantity > 0) < CURRENT_DATE
            THEN 'EXPIRED'
        WHEN MIN(si.expiry_date) FILTER (WHERE si.remaining_quantity > 0)
             <= CURRENT_DATE + 7 THEN 'SOON'
        WHEN COALESCE(SUM(si.remaining_quantity), 0) <= p.min_stock THEN 'LOW'
        ELSE 'OK'
    END AS stock_status
FROM products p
JOIN product_categories c ON c.id = p.category_id
LEFT JOIN supply_items si ON si.product_id = p.id
WHERE p.is_active
GROUP BY p.id, c.name;

COMMIT;
